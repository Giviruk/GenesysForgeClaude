namespace GenesysForge.Application.Dtos;

/// <summary>
/// Ответ маршрута, создающего запись <b>внутри</b> персонажа: позицию инвентаря, транспорт,
/// улучшение, критическое ранение.
///
/// <para>
/// Отдельный тип, а не анонимный <c>new { Id }</c>, чтобы <c>ReturnSheetFilter</c> мог отличить их
/// от маршрутов, создающих <i>другого</i> персонажа — <c>duplicate</c> и <c>import</c> тоже
/// отвечают <c>201 Created</c> с идентификатором, но подменять их частями листа нельзя: части были
/// бы от исходного персонажа, а идентификатор — от копии.
/// </para>
/// </summary>
public record CreatedInCharacterResponse(Guid Id);
