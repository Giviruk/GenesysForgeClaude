namespace GenesysForge.Domain;

/// <summary>
/// Материал магического инструмента (ROT-MAG-MAT-01). Неизменяемое свойство экземпляра: это не
/// улучшение и не качество изготовления, перебрать посох в костяной нельзя. Дуб идёт нулём, чтобы
/// строки, созданные до появления материала, были обычным дубом — он ничего не меняет.
/// </summary>
public enum ImplementMaterial
{
    /// <summary>Дуб: цена и редкость без изменений, триггера нет.</summary>
    Oak = 0,

    /// <summary>Кость: после успешной Атаки или Проклятья лечит заклинателю 1 рану, раз за проверку.</summary>
    Bone = 1,

    /// <summary>Орешник: при триумфе раз за проверку добавляет бросок бонусной кости; триумф остаётся.</summary>
    Hazel = 2,

    /// <summary>Ива: после успешного заклинания добавляет автоматическое преимущество, раз за проверку.</summary>
    Willow = 3,

    /// <summary>Тис: после успешного Усиления, Барьера или Лечения снимает заклинателю 1 усталость.</summary>
    Yew = 4,
}
