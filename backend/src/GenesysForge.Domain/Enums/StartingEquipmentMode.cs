namespace GenesysForge.Domain;

/// <summary>
/// Взаимоисключающие режимы стартового снаряжения (ROT-CRE-03). Смешивать их нельзя:
/// частичный комплект, комплект плюс бюджет и выбор предметов чужой карьеры запрещены.
/// </summary>
public enum StartingEquipmentMode
{
    /// <summary>
    /// Безопасный режим по умолчанию: бюджет 500 silver на стартовые покупки и отдельные
    /// карманные деньги 1d100. Карьерный комплект не выдаётся.
    /// </summary>
    StandardMoney = 0,

    /// <summary>
    /// Только с разрешения GM: вместо бюджета 500 персонаж получает весь комплект своей карьеры
    /// и указанную комплектом сумму денег.
    /// </summary>
    CareerPackage = 1,
}
