namespace GenesysForge.Domain;

/// <summary>
/// Взаимоисключающие режимы стартового снаряжения (ROT-CRE-03). Смешивать их нельзя:
/// частичный комплект, смешанный режим и выбор предметов чужой карьеры запрещены.
/// </summary>
public enum StartingEquipmentMode
{
    /// <summary>
    /// Безопасный режим по умолчанию: персонаж получает 500 монет в обычный кошелёк.
    /// Карьерный комплект не выдаётся.
    /// </summary>
    StandardMoney = 0,

    /// <summary>
    /// Только с разрешения GM: персонаж получает весь комплект своей карьеры и указанную
    /// комплектом сумму денег.
    /// </summary>
    CareerPackage = 1,
}
