namespace GenesysForge.Domain;

/// <summary>
/// Качество изготовления оружия или брони (ROT-WPN-02). У экземпляра оно ровно одно и не
/// складывается: новый тип заменяет предыдущий, а не прибавляется к нему.
/// <para>
/// Значения дописываются в конец: <see cref="Dwarven"/>, <see cref="Elven"/> и <see cref="Steel"/>
/// уже лежат в базе именного оружия (ROT-HA-02) своими номерами, и перенумеровать их нельзя.
/// </para>
/// </summary>
public enum WeaponCraftsmanship
{
    /// <summary>Гномья работа: прочнее и тяжелее.</summary>
    Dwarven = 0,

    /// <summary>Эльфийская работа: легче, но бьёт слабее.</summary>
    Elven = 1,

    /// <summary>Обычная работа: числа таблицы без изменений. Значение по умолчанию для legacy-строк.</summary>
    Steel = 2,

    /// <summary>Железо: дёшево и грубо.</summary>
    Iron = 3,

    /// <summary>Древняя работа: редчайшая и лучшая, всегда редкость 10.</summary>
    Ancient = 4,
}
