namespace GenesysForge.Domain;

/// <summary>
/// Состояние повреждения экземпляра (GEN-EQP-DMG-01). Принадлежит экземпляру, а не записи
/// каталога: помятый шлем остаётся помятым только у своего владельца. Ступени не складываются —
/// предмет находится ровно в одном состоянии, поэтому Незначительное и Умеренное не суммируются.
/// </summary>
public enum ItemDamageState
{
    /// <summary>Цел: штрафов нет, ремонт не нужен.</summary>
    Undamaged = 0,

    /// <summary>Незначительное: одна помеха ко всем проверкам, прямо использующим предмет.</summary>
    Minor = 1,

    /// <summary>Умеренное: сложность таких проверок повышается на одну ступень.</summary>
    Moderate = 2,

    /// <summary>
    /// Серьёзное: предметом нельзя пользоваться. Ни атаки, ни поглощения, ни защиты, ни эффектов
    /// улучшений и инструментов. Физический вес и содержимое контейнера сохраняются.
    /// </summary>
    Major = 3,

    /// <summary>
    /// Уничтожено: пользоваться нельзя, обычный ремонт недоступен — дальше решает ведущий.
    /// </summary>
    Destroyed = 4,
}
