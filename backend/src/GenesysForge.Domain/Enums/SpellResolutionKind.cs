namespace GenesysForge.Domain;

/// <summary>
/// Как применяется эффект заклинания (ROT-MAG-01). Признак структурный, а не вычитанный из
/// описания: «добавляет Жжение, активация 2 преимущества» и «наносит урон усталостью сразу» —
/// разные вещи за столом, и отличать их разбором текста нельзя.
/// </summary>
public enum SpellResolutionKind
{
    /// <summary>Применяется сразу при успехе проверки, ничего активировать не нужно.</summary>
    OnSuccess = 0,

    /// <summary>Даёт оружию или цели свойство, работающее пассивно: «Проникающее», «Оглушающий урон».</summary>
    PassiveQuality = 1,

    /// <summary>
    /// Даёт свойство, которое после броска нужно активировать преимуществами: «Взрыв», «Жжение»,
    /// «Сковывание». Надбавка к сложности покупает возможность, а не само срабатывание.
    /// </summary>
    ActivatedQuality = 2,

    /// <summary>
    /// Сам эффект тратит преимущества или триумф после броска: перемещение цели, дополнительная
    /// цель сверх первой.
    /// </summary>
    AdvantageSpend = 3,

    /// <summary>Требует очка сюжета: «Обмануть смерть».</summary>
    StoryPoint = 4,

    /// <summary>Повествовательный эффект, итог которого описывает ведущий.</summary>
    Narrative = 5,

    /// <summary>
    /// Меняет параметры самого заклинания до броска: дальность, число целей, размер, что именно
    /// можно призвать. На разрешение проверки такой эффект не влияет.
    /// </summary>
    Parameter = 6,
}
