namespace GenesysForge.Domain;

/// <summary>
/// Что улучшение делает с предметом (ROT-EQP-ATT-01). Механика типизирована: клиент присылает
/// только выбор улучшения, а эффект подставляет сервер по коду — объявить своё «Проникающее 9»
/// установкой улучшения нельзя.
/// </summary>
public enum AttachmentEffectKind
{
    /// <summary>
    /// Качество появляется с указанным рейтингом, а если уже есть — растёт на <c>Increment</c>
    /// (Проникающее у Бритвенной кромки: нет — станет 2, есть — плюс один).
    /// </summary>
    GrantOrIncreaseQuality = 0,

    /// <summary>
    /// Качество становится не ниже указанного значения (руны: Жжение не ниже 1, Оглушение не ниже 4).
    /// Это не прибавка: уже более сильное качество не усиливается.
    /// </summary>
    SetQualityAtLeast = 1,

    /// <summary>
    /// Качество выдаётся, но если у предмета есть противоположное — вместо выдачи уменьшается оно
    /// (Балансирный эфес: Неточное −1 вместо Точного +1).
    /// </summary>
    GrantQualityOrCancelOpposite = 2,

    /// <summary>Прибавка к базовому урону оружия.</summary>
    Damage = 3,

    /// <summary>Уменьшение критического значения (не ниже единицы).</summary>
    CritReduction = 4,

    /// <summary>Прибавка к поглощению брони.</summary>
    Soak = 5,

    /// <summary>Прибавка к ближней защите.</summary>
    MeleeDefense = 6,

    /// <summary>Прибавка к дальней защите.</summary>
    RangedDefense = 7,

    /// <summary>Прибавка к весу предмета.</summary>
    Encumbrance = 8,

    /// <summary>Кости умения к проверкам навыка (Позолота, Руна сумерек).</summary>
    SkillBoost = 9,

    /// <summary>
    /// Автоматический символ в проверке навыка (Устрашающий облик). Приложение его не подставляет:
    /// автоматических успехов и провалов в роллере нет, и изображать применённое правило нельзя.
    /// </summary>
    AutomaticSymbol = 10,

    /// <summary>
    /// Эффект существует, но исполнить его нечем: нужен рантайм столкновения (Шипы, Скверна
    /// Инфернаэля, Дуэльная гарда, Руна клинков). Метаданные верные, механика описательная.
    /// </summary>
    NarrativeOnly = 11,
}

/// <summary>Когда эффект улучшения действует.</summary>
public enum AttachmentEffectCondition
{
    /// <summary>Всегда, пока улучшение установлено.</summary>
    Always = 0,

    /// <summary>Только когда предмет надет и выбран активной бронёй (ROT-CMB-02).</summary>
    WornAndActive = 1,
}
