namespace GenesysForge.Domain;

/// <summary>
/// Механика одной траты символов. <see cref="Descriptive"/> — эффект, который приложению нечем
/// исполнить: счётчики раундов, длительности доз, «бонусный куб к следующей проверке» и решения
/// ведущего. Такая трата не исчезает — она попадает в описание созданного предмета и в историю,
/// но числа экземпляра не меняет. Остальные значения считаются по-настоящему.
/// </summary>
public enum CraftingSpendEffect
{
    /// <summary>Только текст: правило есть, исполнять его негде.</summary>
    Descriptive = 0,

    /// <summary>Время проекта меняется на <c>Value</c> единиц (минимум одна).</summary>
    Time = 1,

    /// <summary>Вес результата меняется на <c>Value</c> (минимум 0).</summary>
    Encumbrance = 2,

    /// <summary>Слоты улучшений результата меняются на <c>Value</c> (минимум 0).</summary>
    HardPoints = 3,

    /// <summary>Результату добавляется качество <c>Quality</c> с рейтингом <c>Value</c>.</summary>
    AddQuality = 4,

    /// <summary>
    /// Рейтинг выбранного качества результата растёт на <c>Value</c>. Урон, крит, поглощение и
    /// защита выбору недоступны — так сказано в таблице.
    /// </summary>
    QualityRating = 5,

    /// <summary>Создаётся ещё <c>Value</c> одинаковых экземпляров или доз.</summary>
    ExtraQuantity = 6,

    /// <summary>При каждом повреждении экземпляр теряет на одну ступень больше.</summary>
    Fragile = 7,

    /// <summary>Доза несёт эффект другого зелья строго меньшей редкости (<c>Parameter</c> — его код).</summary>
    CombineDose = 8,

    /// <summary>Время работы уменьшается вдвое (минимум одна единица).</summary>
    TimeHalved = 9,
}
