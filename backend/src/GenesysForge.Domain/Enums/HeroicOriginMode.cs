namespace GenesysForge.Domain;

/// <summary>
/// Способ, которым задано происхождение героической способности (ROT-HA-01).
/// Режим хранится явно: по одним лишь заполненным полям нельзя отличить «выпал один результат»
/// от «второй результат потерян».
/// </summary>
public enum HeroicOriginMode
{
    /// <summary>Одна категория из таблицы d10 — выбранная игроком или выпавшая.</summary>
    Standard = 0,

    /// <summary>Две категории из таблицы d10 — результат специального броска «0».</summary>
    DoubleStandard = 1,

    /// <summary>Собственный текст происхождения вместо категорий таблицы.</summary>
    Custom = 2,
}
