namespace GenesysForge.Domain;

/// <summary>
/// Что даёт Improved именного оружия (ROT-HA-05): ровно одно из двух, навсегда и неизменяемо.
/// Древняя работа заменяет прежнее качество изготовления, а не прибавляется к нему, и приносит
/// с собой Укреплённое — поэтому взять оба варианта нельзя, книга даёт выбор.
/// </summary>
public enum SignatureWeaponImprovement
{
    /// <summary>Улучшение ещё не куплено или выбор не сделан.</summary>
    None = 0,

    /// <summary>Качество «Укреплённое» поверх нынешней работы.</summary>
    Reinforced = 1,

    /// <summary>Древняя работа со всеми её эффектами, включая минус слот улучшений.</summary>
    Ancient = 2,
}
