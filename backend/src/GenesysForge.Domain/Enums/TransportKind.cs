namespace GenesysForge.Domain;

/// <summary>
/// Тип транспорта (ROT-TRANSPORT-01). Скакун и повозка живут в одном каталоге профилей и в одном
/// разделе листа: у обоих есть soak, порог, защита, силуэт и вместимость груза, и разводить их по
/// двум параллельным сущностям ради единственной повозки книги нечем.
/// </summary>
public enum TransportKind
{
    /// <summary>Живой скакун: у него есть характеристики, навыки и собственные атаки.</summary>
    Mount = 0,

    /// <summary>
    /// Транспортное средство: характеристик и навыков нет, порог усталости профиля читается как
    /// порог систем, а движение обеспечивает тягловое животное.
    /// </summary>
    Vehicle = 1,
}
